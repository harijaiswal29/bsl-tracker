import { test } from 'node:test';
import assert from 'node:assert/strict';
import { importGlucoseCSV, parseDateTime, detectDateOrder, parseCSV } from '../js/importers.js';

const local = (y, mo, d, h = 0, mi = 0) => new Date(y, mo - 1, d, h, mi).getTime();

test('parseDateTime handles the formats meters export', () => {
  assert.equal(parseDateTime('24-10-2026 08:15', 'DMY'), local(2026, 10, 24, 8, 15));
  assert.equal(parseDateTime('10-24-2026 08:15 PM', 'MDY'), local(2026, 10, 24, 20, 15));
  assert.equal(parseDateTime('12/01/2026 12:05 AM', 'MDY'), local(2026, 12, 1, 0, 5));
  assert.equal(parseDateTime('2026-10-24T13:05:00'), local(2026, 10, 24, 13, 5));
  assert.equal(parseDateTime('24.10.2026 13:05'), local(2026, 10, 24, 13, 5));
  assert.equal(parseDateTime('Oct 24, 2026 1:05:00 PM'), local(2026, 10, 24, 13, 5));
  assert.equal(parseDateTime('24 Oct 2026 07:30'), local(2026, 10, 24, 7, 30));
  assert.ok(Number.isNaN(parseDateTime('31-02-2026 10:00', 'DMY')));
  assert.ok(Number.isNaN(parseDateTime('not a date')));
});

test('detectDateOrder', () => {
  assert.equal(detectDateOrder(['05-10-2026', '24-10-2026']), 'DMY');
  assert.equal(detectDateOrder(['10-05-2026', '10-24-2026']), 'MDY');
  assert.equal(detectDateOrder(['05-10-2026', '06-10-2026']), null);
});

test('parseCSV handles quotes and CRLF', () => {
  assert.deepEqual(parseCSV('a,"b, c","d ""e"""\r\n1,2,3\r\n'), [['a', 'b, c', 'd "e"'], ['1', '2', '3']]);
});

const LIBRE_HEAD = 'Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL,Non-numeric Rapid-Acting Insulin,Rapid-Acting Insulin (units),Non-numeric Food,Carbohydrates (grams),Carbohydrates (servings),Non-numeric Long-Acting Insulin,Long-Acting Insulin Value (units),Notes,Strip Glucose mg/dL,Ketone mmol/L,Meal Insulin (units),Correction Insulin (units),User Change Insulin (units)';
const row = (ts, type, hist = '', scan = '', strip = '') =>
  `FreeStyle LibreLink,ABC-123,${ts},${type},${hist},${scan},,,,,,,,,${strip},,,,`;

test('LibreView CSV (India / day-first)', () => {
  const csv = [
    'Glucose Data,Generated on,24-10-2026 18:00 UTC,Generated by,Hari',
    LIBRE_HEAD,
    row('24-10-2026 08:00', 0, '102'),
    row('24-10-2026 08:15', 0, '118'),
    row('24-10-2026 08:20', 1, '', '125'),
    row('24-10-2026 08:30', 0, 'HI'),
    row('24-10-2026 09:00', 2, '', '', '140'),
    row('24-10-2026 09:05', 6),
  ].join('\n');
  const r = importGlucoseCSV(csv);
  assert.match(r.format, /LibreView/);
  assert.equal(r.readings.length, 4);
  assert.equal(r.skipped, 1);
  assert.deepEqual(r.readings.map((x) => x.kind), ['cgm', 'cgm', 'scan', 'strip']);
  assert.equal(r.readings[0].ts, local(2026, 10, 24, 8, 0));
  assert.equal(r.readings[3].mgdl, 140);
  // stable ids => re-importing the same file creates no duplicates
  assert.deepEqual(importGlucoseCSV(csv).readings.map((x) => x.id), r.readings.map((x) => x.id));
});

test('LibreView CSV (US, mmol/L, AM/PM)', () => {
  const head = LIBRE_HEAD.replace(/mg\/dL/g, 'mmol/L');
  const csv = ['Glucose Data,Generated on,10-24-2026', head, row('10-24-2026 01:15 PM', 0, '5.6'), row('10-24-2026 01:30 PM', 0, '7.0')].join('\n');
  const r = importGlucoseCSV(csv);
  assert.equal(r.readings[0].ts, local(2026, 10, 24, 13, 15));
  assert.equal(r.readings[0].mgdl, 101);
  assert.equal(r.readings[1].mgdl, 126);
});

test('generic meter CSV (mySugr-style)', () => {
  const csv = [
    'Date,Time,Tags,Blood Sugar Measurement (mg/dL),Insulin Injection Units (Pump),Note',
    '"Oct 24, 2026",8:02:00 AM,Before Breakfast,108,,',
    '"Oct 24, 2026",10:05:00 AM,After Breakfast,171,,',
    '"Oct 24, 2026",1:00:00 PM,,,,"no reading"',
  ].join('\n');
  const r = importGlucoseCSV(csv);
  assert.match(r.format, /Blood Sugar Measurement/);
  assert.equal(r.readings.length, 2);
  assert.equal(r.readings[1].ts, local(2026, 10, 24, 10, 5));
  assert.equal(r.readings[1].mgdl, 171);
  assert.equal(r.readings[1].kind, 'meter');
});

test('generic semicolon CSV with decimal commas in mmol/L', () => {
  const csv = 'Datum/Date;Uhrzeit/Time;Glucose (mmol/L)\n24.10.2026;07:45;6,2\n24.10.2026;09:45;9,1\n';
  const r = importGlucoseCSV(csv);
  assert.equal(r.readings.length, 2);
  assert.equal(r.readings[0].mgdl, 112);
  assert.equal(r.readings[0].ts, local(2026, 10, 24, 7, 45));
});

test('unrecognised file throws a friendly error', () => {
  assert.throws(() => importGlucoseCSV('name,age\nbob,3'), /glucose column/);
});
